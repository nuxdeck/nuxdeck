// SPDX-License-Identifier: Apache-2.0

// Package boundary enforces the licence split from ADR-006: every Go file
// carries an SPDX header matching its directory, and Apache-2.0 code never
// imports AGPL-3.0 code.
package boundary

import (
	"fmt"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

const (
	modulePath = "github.com/nuxdeck/nuxdeck"
	agpl       = "AGPL-3.0-only"
	apache     = "Apache-2.0"
)

// agplDirs are the only AGPL-3.0 Go trees; everything else is Apache-2.0.
var agplDirs = []string{"cmd/nuxd", "internal/server"}

func under(rel, dir string) bool {
	return rel == dir || strings.HasPrefix(rel, dir+"/")
}

func expectedLicence(rel string) string {
	for _, d := range agplDirs {
		if under(rel, d) {
			return agpl
		}
	}
	return apache
}

// checkFile validates one Go source file addressed by its slash-separated
// path relative to the repository root.
func checkFile(rel string, src []byte) error {
	if strings.Contains(firstLines(src, 5), "Code generated") {
		return nil
	}

	want := expectedLicence(rel)
	header := "// SPDX-License-Identifier: " + want
	if first, _, _ := strings.Cut(string(src), "\n"); strings.TrimSpace(first) != header {
		return fmt.Errorf("%s: first line must be %q", rel, header)
	}

	if want != apache {
		return nil
	}
	f, err := parser.ParseFile(token.NewFileSet(), rel, src, parser.ImportsOnly)
	if err != nil {
		return fmt.Errorf("%s: parse imports: %w", rel, err)
	}
	for _, imp := range f.Imports {
		p, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			return fmt.Errorf("%s: bad import path %s: %w", rel, imp.Path.Value, err)
		}
		for _, d := range agplDirs {
			if under(strings.TrimPrefix(p, modulePath+"/"), d) && strings.HasPrefix(p, modulePath+"/") {
				return fmt.Errorf("%s: Apache-2.0 code must not import AGPL-3.0 package %s", rel, p)
			}
		}
	}
	return nil
}

func firstLines(src []byte, n int) string {
	lines := strings.SplitN(string(src), "\n", n+1)
	if len(lines) > n {
		lines = lines[:n]
	}
	return strings.Join(lines, "\n")
}

func TestCheckFile(t *testing.T) {
	tests := []struct {
		name    string
		rel     string
		src     string
		wantErr bool
	}{
		{"agpl server ok", "internal/server/x.go", "// SPDX-License-Identifier: AGPL-3.0-only\npackage x\n", false},
		{"apache agent ok", "internal/agent/x.go", "// SPDX-License-Identifier: Apache-2.0\npackage x\n", false},
		{"missing header", "internal/agent/x.go", "package x\n", true},
		{"wrong licence for dir", "internal/agent/x.go", "// SPDX-License-Identifier: AGPL-3.0-only\npackage x\n", true},
		{"server header in apache dir", "pkg/client/x.go", "// SPDX-License-Identifier: AGPL-3.0-only\npackage x\n", true},
		{"apache imports server", "internal/agent/x.go", "// SPDX-License-Identifier: Apache-2.0\npackage x\n\nimport _ \"github.com/nuxdeck/nuxdeck/internal/server/store\"\n", true},
		{"apache imports nuxd", "pkg/x.go", "// SPDX-License-Identifier: Apache-2.0\npackage x\n\nimport _ \"github.com/nuxdeck/nuxdeck/cmd/nuxd\"\n", true},
		{"apache imports nux ok", "pkg/x.go", "// SPDX-License-Identifier: Apache-2.0\npackage x\n\nimport _ \"github.com/nuxdeck/nuxdeck/cmd/nux\"\n", false},
		{"agpl may import apache", "internal/server/x.go", "// SPDX-License-Identifier: AGPL-3.0-only\npackage x\n\nimport _ \"github.com/nuxdeck/nuxdeck/proto/nuxdeck/agent/v1\"\n", false},
		{"generated file skipped", "proto/x.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := checkFile(tt.rel, []byte(tt.src))
			if (err != nil) != tt.wantErr {
				t.Fatalf("checkFile() error = %v, wantErr %v", err, tt.wantErr)
			}
		})
	}
}

func TestRepositoryFiles(t *testing.T) {
	root, err := os.OpenRoot(filepath.Join("..", ".."))
	if err != nil {
		t.Fatalf("open repository root: %v", err)
	}
	t.Cleanup(func() {
		if err := root.Close(); err != nil {
			t.Errorf("close repository root: %v", err)
		}
	})

	fsys := root.FS()
	err = fs.WalkDir(fsys, ".", func(rel string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "node_modules", "vendor":
				return fs.SkipDir
			}
			return nil
		}
		if path.Ext(rel) != ".go" {
			return nil
		}
		src, err := fs.ReadFile(fsys, rel)
		if err != nil {
			return fmt.Errorf("read %s: %w", rel, err)
		}
		if err := checkFile(rel, src); err != nil {
			t.Error(err)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk repository: %v", err)
	}
}
