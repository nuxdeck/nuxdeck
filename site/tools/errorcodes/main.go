// Command errorcodes regenerates site/reference/error-codes.md from the error
// code registry in internal/errcode. Run it from the repository root:
//
//	go run ./site/tools/errorcodes          # write the page
//	go run ./site/tools/errorcodes -check   # exit 1 if the page is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/nuxdeck/nuxdeck/internal/errcode"
)

const defaultOut = "site/reference/error-codes.md"

func main() {
	out := flag.String("out", defaultOut, "page to write or check")
	check := flag.Bool("check", false, "fail if the page on disk differs from the registry instead of writing it")
	flag.Parse()

	if err := run(*out, *check); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, "errorcodes:", err)
		os.Exit(1)
	}
}

func run(out string, check bool) error {
	want := Render(errcode.Entries())
	if check {
		have, err := os.ReadFile(out) //nolint:gosec // developer-supplied output path
		if err != nil {
			return fmt.Errorf("read %s: %w", out, err)
		}
		if !bytes.Equal(have, want) {
			return fmt.Errorf("%s is stale; run go run ./site/tools/errorcodes", out)
		}
		return nil
	}
	if err := os.WriteFile(out, want, 0o644); err != nil { //nolint:gosec // generated documentation, meant to be readable
		return fmt.Errorf("write %s: %w", out, err)
	}
	return nil
}

// Render returns the reference page for entries, sorted by code so that
// reordering the registry does not churn the page.
func Render(entries []errcode.Entry) []byte {
	sorted := slices.Clone(entries)
	slices.SortFunc(sorted, func(a, b errcode.Entry) int { return strings.Compare(string(a.Code), string(b.Code)) })

	var b bytes.Buffer
	b.WriteString("---\ntitle: Error codes\ndescription: Every stable error code, its meaning and what to do.\nweight: 90\n---\n\n")
	b.WriteString("<!-- Generated by site/tools/errorcodes from internal/errcode/codes.go. Do not edit by hand. -->\n\n")
	b.WriteString("Every error that reaches a user, a log reader or the API carries one of these codes. ")
	b.WriteString("Codes never change meaning once released. The same code appears in the `error.code` field of API responses and in the output of the `nux` and `nuxd` commands.\n\n")
	b.WriteString("| Code | Title | Message | Hint |\n|---|---|---|---|\n")
	for _, e := range sorted {
		_, _ = fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", e.Code, cell(e.Title), cell(e.Message), cell(e.Hint))
	}
	return b.Bytes()
}

// cell escapes a value for a Markdown table cell.
func cell(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}
